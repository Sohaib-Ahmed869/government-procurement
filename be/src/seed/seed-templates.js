// can be looked at with something in it, and every record says so on the card:
// each carries "PREVIEW SAMPLE" in its source line, which the page prints.
//
// It is seeded as PUBLISHED, which is the only way to see the page as a visitor
// will. Drafts would not do: a public page reads the learner token slot, not the
// admin one (see currentScope in fe/src/api/client.js), so a signed-in CMS admin
// browsing /templates sends no staff token and would see nothing.
//
// The documents are generated here rather than sourced, so the licence really is
// "created in-house" and nothing is being passed off as somebody else's work.
// `confirmedBy` says in as many words that it is not a sign-off.
//
// DELETE IT BEFORE THE SITE GOES LIVE: npm run seed:templates -- --remove
//
// PowerPoint is absent on purpose. A valid .pptx needs a slide master, a layout
// and a theme, and a hand-rolled minimal deck is the one most likely to be
// rejected by PowerPoint itself. Shipping a file that will not open is worse
// than showing the format with nothing under it, so the format filter will read
// zero for PowerPoint until a real deck is uploaded through the CMS.
