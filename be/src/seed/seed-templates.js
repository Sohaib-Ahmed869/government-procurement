const EXT = { word: 'docx', excel: 'xlsx' };
const MIME = {
  word: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  excel: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
};

async function remove() {
  const existing = await Template.find({ source: SOURCE });
  for (const t of existing) {
    if (t.file?.key) await deleteObject(t.file.key).catch(() => {});
  }
  const res = await Template.deleteMany({ source: SOURCE });
  console.log(`[seed-templates] removed ${res.deletedCount} preview templates and their files.`);
}

async function run() {
  await connectDB();

  if (process.argv.includes('--remove')) {
    await remove();
    await disconnectDB();
    return;
  }

  // Replace rather than duplicate, so re-running is safe.
  await remove();

  let created = 0;
  for (const item of SET) {
    const { build, licence, ...fields } = item;
    const buffer = build();
    const filename = `${item.title}.${EXT[item.format]}`;

    const { key, url } = await uploadBuffer({
      buffer,
      mimeType: MIME[item.format],
      folder: 'templates',
      originalName: filename,
    });

    await Template.create({
      ...fields,
      source: SOURCE,
      licence: licence || LICENCE,
      file: { key, url, name: filename, size: buffer.length, mime: MIME[item.format] },
      // Published on purpose: see the note at the top of this file.
      status: 'published',
    });
    created += 1;
    console.log(`[seed-templates] ${item.format.padEnd(6)} ${item.title} (${buffer.length} bytes)`);
  }

  console.log(`[seed-templates] done. ${created} preview templates published.`);
  console.log('[seed-templates] These are PREVIEW SAMPLES. Remove before launch:');
  console.log('[seed-templates]   npm run seed:templates -- --remove');

  await disconnectDB();
}

run().catch((err) => {
  console.error('[seed-templates] failed:', err);
  process.exit(1);
});
